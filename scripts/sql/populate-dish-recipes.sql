## Coq au Vin

**Serves 4 | Prep 25 minutes | Cook about 1 hour 20 minutes**

### Ingredients
- 8 chicken thighs, patted dry
- 100 g bacon lardons
- 12 pearl onions, peeled
- 2 carrots, sliced; 2 garlic cloves, minced
- 250 g cremini mushrooms, halved
- 2 tbsp flour and 25 g unsalted butter
- 600 ml red wine and 150 ml chicken stock
- 3 thyme sprigs, 2 bay leaves, salt and black pepper
- 2 tbsp olive oil

### Method
1. Heat 1 tbsp oil in a heavy casserole and brown the bacon. Remove, then brown the onions and chicken in batches, adding more oil as needed. Set aside.
2. Cook carrots and garlic briefly. Stir in flour and butter, then gradually pour in wine and stock, scraping up browned bits. Add thyme, bay, bacon, onions, and chicken.
3. Cover and simmer gently for 50-60 minutes, until the chicken is cooked through and tender.
4. Meanwhile, sauté mushrooms in a little oil until golden. Stir them into the casserole for the final 10 minutes. Season and serve.

Recipe reference: https://www.bbcgoodfood.com/recipes/coq-au-vin
