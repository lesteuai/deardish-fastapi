## Baja Fish Tacos

**Makes 8 tacos | Prep 20 minutes | Cook 15 minutes**

### Ingredients
- 700 g firm white fish, cut into strips
- 8 corn tortillas
- 1/2 small cabbage, finely shredded
- 1/2 red onion, thinly sliced; 1 avocado, sliced
- 2 tbsp lime juice, plus wedges to serve
- 1/2 cup chipotle mayonnaise
- 1/2 cup flour, 1 tsp ground cumin, 1 tsp smoked paprika
- 180 ml cold sparkling water, neutral oil for frying
- Cilantro, salt, and black pepper

### Method
1. Toss cabbage with lime juice and a pinch of salt. Set aside. Pat fish dry and season with salt, pepper, cumin, and paprika.
2. Whisk flour with sparkling water and a pinch of salt to make a smooth, pourable batter. Heat 2-3 cm oil in a deep pan to 175-190°C.
3. Dip fish in batter and fry in batches for 3-5 minutes, turning once, until crisp and cooked through. Drain on a rack or paper towels.
4. Warm tortillas. Fill with fish, cabbage, red onion, avocado, chipotle mayonnaise, and cilantro. Serve with lime.

Recipe reference: https://www.seriouseats.com/baja-fish-tacos-recipe-8682282
