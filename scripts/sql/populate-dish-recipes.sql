## Thai Green Curry

**Serves 4 | Prep 10 minutes | Cook 20 minutes**

### Ingredients
- 450 g chicken breast, cut into bite-size pieces
- 1 tbsp neutral oil and 2 tbsp Thai green curry paste
- 400 ml coconut milk
- 1 red bell pepper, sliced; 150 g bamboo shoots, drained
- 2 kaffir lime leaves, torn
- 1 tbsp fish sauce and 1 tsp palm sugar, to taste
- A handful of Thai basil leaves
- Steamed jasmine rice and lime wedges, to serve

### Method
1. Heat oil in a wok over medium-high heat. Fry curry paste for 1-2 minutes until fragrant.
2. Add chicken and stir to coat. Cook until lightly browned, then add coconut milk and lime leaves. Bring to a gentle simmer.
3. Simmer 8-10 minutes, until chicken is cooked through. Add bell pepper and bamboo shoots for the final 3-4 minutes.
4. Season with fish sauce and palm sugar. Stir in basil and serve with rice and lime.

Recipe reference: https://www.bbc.co.uk/food/recipes/thaigreenchickencurr_92440
