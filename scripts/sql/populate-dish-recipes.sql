## Tuscan Ribollita

**Serves 4 | Prep 15 minutes | Cook 35 minutes**

### Ingredients
- 2 tbsp extra-virgin olive oil, plus more to serve
- 1 yellow onion, diced
- 1 carrot and 2 celery stalks, diced
- 2 garlic cloves, minced
- 1 rosemary sprig
- 1 (400 g) can crushed tomatoes
- 500 ml vegetable stock
- 1 (400 g) can cannellini beans, drained and rinsed
- 250 g lacinato kale, chopped
- 150 g stale sourdough, torn into chunks
- 1 tbsp red-wine vinegar, salt and black pepper

### Method
1. Warm the oil in a heavy pot. Cook onion, carrot, and celery with a pinch of salt for 12-15 minutes until soft. Add garlic and rosemary; cook for 1 minute.
2. Stir in tomatoes, stock, and beans. Bring to a simmer, add kale, cover, and cook for 10 minutes.
3. Stir in bread and simmer until softened and the stew is thick, about 5 minutes. Stir in vinegar, season to taste, and serve with olive oil.

Recipe reference: https://www.bbcgoodfood.com/recipes/tuscan-style-ribollita
