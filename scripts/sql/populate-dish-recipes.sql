## Chana Masala

**Serves 4-6 | Prep 10 minutes | Cook 45 minutes**

### Ingredients
- 2 tbsp neutral oil or ghee
- 1 large yellow onion, finely diced
- 4 garlic cloves, 1-inch piece fresh ginger, and 1-2 green chilies
- 2 tsp whole cumin seeds, 2 tsp ground coriander, 1/2 tsp turmeric
- 1 1/2 tsp garam masala, divided
- 1 (400 g) can whole tomatoes
- 2 (400 g) cans chickpeas, drained and rinsed
- 1 tbsp lemon juice, 1/2 cup chopped cilantro, salt

### Method
1. Pound or blend garlic, ginger, chilies, lemon juice, and a pinch of salt into a paste.
2. Heat oil in a saucepan. Toast cumin seeds until fragrant, add onion, and cook until deeply browned, about 10 minutes. Add a splash of water as needed to loosen browned bits.
3. Add the aromatics paste, coriander, turmeric, and 1 tsp garam masala. Stir for 30 seconds. Add tomatoes, crush them, then stir in chickpeas, cilantro, and 1/2 cup water.
4. Simmer partially covered for about 30 minutes, stirring occasionally, until thick. Finish with remaining garam masala and lemon juice; season and serve with rice or naan.

Recipe reference: https://www.seriouseats.com/channa-masala-recipe
