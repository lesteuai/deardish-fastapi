## Miso-Glazed Salmon

**Serves 4 | Prep 10 minutes | Cook 5-8 minutes**

### Ingredients
- 4 salmon fillets, about 150 g each
- 3 tbsp white miso
- 2 tbsp mirin
- 1 tbsp brown sugar
- 1 tsp finely grated fresh ginger
- 1 tbsp neutral oil
- 2 scallions, thinly sliced; toasted sesame seeds, to finish
- 300 g sushi rice, cooked to package directions

### Method
1. Whisk miso, mirin, brown sugar, ginger, and oil. Coat the salmon and marinate for 30 minutes, or cook immediately.
2. Heat the broiler to high. Wipe excess marinade from the fish and arrange on a foil-lined tray. Broil about 5-8 minutes, until browned and cooked to your preferred doneness.
3. Serve over rice with scallions and sesame seeds.

Recipe reference: https://www.seriouseats.com/miso-glazed-salmon-in-the-toaster-oven-recipe
